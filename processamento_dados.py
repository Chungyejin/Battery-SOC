# ===============================
# 5. CALCULAR SOC POR CICLO (COM NORMALIZAÇÃO)
# ===============================
def calcular_soc(grupo):
    capacidade = grupo['capacidade_ah'].iloc[0]

    # Coulomb Counting
    grupo['delta_soc'] = (-grupo['CURRENT(A)'] * grupo['delta_t_h']) / capacidade

    # SOC bruto
    grupo['SOC'] = 1 - grupo['delta_soc'].cumsum()

    # 🔥 NORMALIZAÇÃO (ESSENCIAL)
    soc_max = grupo['SOC'].max()
    soc_min = grupo['SOC'].min()

    # evitar divisão por zero
    if soc_max != soc_min:
        grupo['SOC'] = (grupo['SOC'] - soc_min) / (soc_max - soc_min)
    else:
        grupo['SOC'] = 0  # ciclo degenerado

    return grupo

df_final = df_final.groupby(['cell_id', 'cycle_id'], group_keys=False).apply(calcular_soc)

