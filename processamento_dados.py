import gymnasium as gym
from gymnasium import spaces
import numpy as np
import pandas as pd

class BatteryEnv(gym.Env):

    def __init__(self, df):
        super(BatteryEnv, self).__init__()

        self.df = df
        self.current_step = 0

        # Features
        self.features = [
            'VOLTAGE',
            'CURRENT',
            'POWER',
            'RESISTANCE',
            'NTC_TEMP'
        ]

        # Espaço de estados
        self.observation_space = spaces.Box(
            low=-np.inf,
            high=np.inf,
            shape=(len(self.features),),
            dtype=np.float32
        )

        # Ação = SOC estimado
        self.action_space = spaces.Box(
            low=0.0,
            high=100.0,
            shape=(1,),
            dtype=np.float32
        )

    def reset(self, seed=None, options=None):
        self.current_step = 0

        obs = self.df.loc[self.current_step, self.features].values.astype(np.float32)

        return obs, {}

    def step(self, action):

        soc_real = self.df.loc[self.current_step, 'SOC']

        soc_pred = action[0]

        # Reward
        reward = -((soc_real - soc_pred) ** 2)

        self.current_step += 1

        done = self.current_step >= len(self.df) - 1

        if not done:
            obs = self.df.loc[self.current_step, self.features].values.astype(np.float32)
        else:
            obs = np.zeros(len(self.features), dtype=np.float32)

        return obs, reward, done, False, {}

